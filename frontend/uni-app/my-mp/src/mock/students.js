/**
 * 模拟 GET /api/teacher/student/list
 * 参数和返回结构完全照契约来，这样切到真接口时页面不用改。
 * @param {{ keyword?: string, status?: number }} params
 */
export function mockStudentList(params = {}) {
  const { keyword = '', status = 1 } = params
  const k = String(keyword).trim().toLowerCase()

  let list = ALL
  /* status = -1 表示全部，和契约一致 */
  if (status !== -1) {
    list = list.filter((s) => s.status === status)
  }
  if (k) {
    list = list.filter(
      (s) =>
        s.name.toLowerCase().includes(k) ||
        (s.studentNo || '').toLowerCase().includes(k)
    )
  }

  /* 学号为空的排最后，和契约里的 ORDER BY student_no IS NULL, student_no 对齐 */
  list = [...list].sort((a, b) => {
    if (!a.studentNo && !b.studentNo) return a.id - b.id
    if (!a.studentNo) return 1
    if (!b.studentNo) return -1
    return a.studentNo.localeCompare(b.studentNo)
  })

  return { total: list.length, list }
}
